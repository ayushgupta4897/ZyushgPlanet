import pandas as pd, numpy as np
pd.set_option('display.width',250)
rb=[1,1.5,2,4,100]; rl=['1-1.5','1.5-2','2-4','>4']
koi=pd.read_csv('dl/koi_cumulative.csv')
k=koi[(koi.koi_steff<4000)&koi.koi_disposition.isin(['CANDIDATE','CONFIRMED'])].copy()
print("KOI (cumulative) cool hosts Teff<4000, CANDIDATE+CONFIRMED:", len(k), "; hosts:", k.kepid.nunique())
k['rbin']=pd.cut(k.koi_prad,rb,labels=rl); k['pbin']=pd.cut(k.koi_period,[0,10,50,200,1e4],labels=['<10','10-50','50-200','>200'])
print(pd.crosstab(k.rbin,k.pbin,margins=True))
k['kpbin']=pd.cut(k.koi_kepmag,[0,14,15,16,17,20],labels=['<14','14-15','15-16','16-17','>17'])
print("by Kp:"); print(pd.crosstab(k.kpbin,k.rbin,margins=True))
print("KOI cool hosts with P<50 & Rp>2:", ((k.koi_period<50)&(k.koi_prad>2)).sum(), "; P<50 & Rp 1-2:", ((k.koi_period<50)&(k.koi_prad>=1)&(k.koi_prad<=2)).sum())
print("KOI depth quantiles (ppm) cool hosts:", k.koi_depth.quantile([.1,.5,.9]).round(0).to_dict(), "model SNR quantiles:", k.koi_model_snr.quantile([.1,.5,.9]).round(1).to_dict())
print("Kp>15.5 cool-host KOIs:", (k.koi_kepmag>15.5).sum(), "of which Rp>2 & P<50:", ((k.koi_kepmag>15.5)&(k.koi_prad>2)&(k.koi_period<50)).sum())
toi=pd.read_csv('dl/toi.csv')
t=toi[(toi.st_teff<4000)&~toi.tfopwg_disp.isin(['FP','FA'])].copy()
print("\nTOI cool hosts Teff<4000 excl FP/FA:", len(t), "dispositions:", t.tfopwg_disp.value_counts().to_dict())
t['rbin']=pd.cut(t.pl_rade,rb,labels=rl); t['pbin']=pd.cut(t.pl_orbper,[0,10,50,200,1e4],labels=['<10','10-50','50-200','>200'])
print(pd.crosstab(t.rbin,t.pbin,margins=True))
t['tbin']=pd.cut(t.st_tmag,[0,10,11,12,13,14,15,20],labels=['<10','10-11','11-12','12-13','13-14','14-15','>15'])
print("by Tmag:"); print(pd.crosstab(t.tbin,t.rbin,margins=True))
t['dbin']=pd.cut(t.st_dist,[0,30,50,100,1e4],labels=['<30','30-50','50-100','>100'])
print("by distance:"); print(pd.crosstab(t.dbin,t.rbin,margins=True))
print("TOI cool hosts d<100 pc, P<50 d, Rp>=1 (excl FP/FA):", ((t.st_dist<100)&(t.pl_orbper<50)&(t.pl_rade>=1)).sum(), "; Rp>2:", ((t.st_dist<100)&(t.pl_orbper<50)&(t.pl_rade>2)).sum())
print("TOI cool hosts Tmag<15 P<50 Rp>=1:", ((t.st_tmag<15)&(t.pl_orbper<50)&(t.pl_rade>=1)).sum())
print("TOI depth quantiles ppm cool hosts:", t.pl_trandep.quantile([.1,.5,.9]).round(0).to_dict())
k2=pd.read_csv('dl/k2pandc.csv')
k2c=k2[(k2.st_teff<4000)&(k2.disposition.isin(['CANDIDATE','CONFIRMED']))]
print("\nK2 cool hosts CANDIDATE+CONFIRMED rows:", len(k2c), "unique planets:", k2c.pl_name.nunique(), "unique hosts:", k2c.epic_hostname.nunique())
print(k2c.drop_duplicates('pl_name').assign(rbin=lambda d: pd.cut(d.pl_rade,rb,labels=rl), pbin=lambda d: pd.cut(d.pl_orbper,[0,10,50,200,1e4],labels=['<10','10-50','50-200','>200'])).pipe(lambda d: pd.crosstab(d.rbin,d.pbin,margins=True)))
print("K2 cool hosts Kp quantiles:", k2c.drop_duplicates('epic_hostname').sy_kepmag.quantile([.1,.5,.9]).round(1).to_dict())
